import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('real DiTing zero results remain searchable and pathway KO links share sample evidence', async ({ page }) => {
  test.skip(!process.env.AD_META_E2E_DITING_ROOT, 'Needs isolated real DiTing source fixture');
  test.setTimeout(120000);
  const errors=[]; page.on('pageerror', e=>errors.push(e.message)); page.on('console',m=>{ if(['error','warning'].includes(m.type())) errors.push(m.text()); });
  await page.setViewportSize({width:1600,height:1100});
  await page.goto('/analysis/abundance?dataset=ad-nc-ko-abundance&chart=differential_ko');
  const panel=page.getByRole('region',{name:'KO 与通路研究对象联动'});
  await expect(panel).toBeVisible({timeout:60000});
  await expect(panel).toContainText('源对象 9537 项，进入检验 5948 项');
  await expect(panel).toContainText('通过 0 项');
  await panel.getByLabel('搜索功能对象').fill('K15864');
  await panel.getByRole('button',{name:'K15864',exact:true}).click();
  const evidence=panel.getByRole('region',{name:'功能对象样本证据'});
  await expect(evidence).toContainText('未通过当前 q 阈值或未纳入检验');
  await expect(evidence).toContainText('AD：n=122，检出 1/122');
  await expect(evidence).toContainText('NC：n=63，检出 1/63');
  await evidence.getByRole('button',{name:'返回已核验关联通路'}).click();
  await expect(evidence).toContainText('K00368 + K15864');
  await expect(evidence).toContainText('AD：n=122，检出 58/122');
  await expect(evidence).toContainText('最大绝对差 0.0000');
  await panel.getByLabel('搜索功能对象').fill('');
  await evidence.scrollIntoViewIfNeeded(); await evidence.screenshot({path:'/private/tmp/opt008-functional-desktop.png'});
  const svgEvent=page.waitForEvent('download'); await evidence.getByRole('button',{name:'导出所选分布 SVG'}).click();
  const svg=await readFile(await(await svgEvent).path(),'utf8'); expect(svg).toContain('<svg');
  const download=page.waitForEvent('download');
  await panel.getByRole('button',{name:'下载所选对象样本原值 CSV'}).click();
  const csv=await readFile(await(await download).path(),'utf8');expect(csv.trim().split('\r\n')).toHaveLength(186);
  const statsDownload=page.waitForEvent('download');await panel.getByRole('button',{name:'下载本类全部统计 CSV'}).click();
  expect((await readFile(await(await statsDownload).path(),'utf8')).trim().split('\r\n')).toHaveLength(96);
  await evidence.getByRole('button',{name:'查看 K00368'}).click();
  await expect(evidence).toContainText('NC：n=63，检出 41/63');
  await evidence.getByLabel('仅显示变换 log10(x+1)（原值统计与下载不变）').check();
  await expect(evidence).toContainText('p=');
  await page.setViewportSize({width:390,height:844});await evidence.scrollIntoViewIfNeeded();
  await expect.poll(() => evidence.locator('canvas').first().evaluate(c => c.clientWidth)).toBeLessThan(350);
  await page.screenshot({path:'/private/tmp/opt008-functional-mobile.png'});
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);expect(errors).toEqual([]);
  await page.setViewportSize({width:1600,height:1100});
  await page.goto('/analysis/abundance?dataset=ad-nc-ko-abundance&chart=ditingOverview');
  await page.getByText('KO 与通路证据联动（固定全队列）',{exact:true}).click();
  await expect(page.getByRole('region',{name:'KO 与通路研究对象联动'})).toContainText('源对象 95 项');
});
